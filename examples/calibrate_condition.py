"""Evaluate condition-number alert thresholds on held-out deletion paths."""

import argparse
import csv
import json
from pathlib import Path

THRESHOLDS = (1e4, 1e6, 1e8, 1e10, 1e12, 1e14)
TRAIN = {"42", "43", "44"}
TEST = {"45", "46", "47"}


def counts(rows, threshold):
    tp = fp = fn = tn = 0
    for row in rows:
        value = float(row["condition_before_rebuild"]) if row["condition_before_rebuild"] else float("inf")
        alert = value > threshold
        failure = row["failure"] == "True"
        tp += alert and failure
        fp += alert and not failure
        fn += not alert and failure
        tn += not alert and not failure
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("steps", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with args.steps.open(encoding="utf-8", newline="") as stream:
        rows = [row for row in csv.DictReader(stream) if row["method"] == "condition"]
    training = [row for row in rows if row["seed"] in TRAIN]
    validation = [row for row in rows if row["seed"] in TEST]
    if not training or not validation:
        parser.error("expected both training and held-out seeds")
    candidates = [{"threshold": threshold, "counts": counts(training, threshold)} for threshold in THRESHOLDS]
    # Minimize missed failures first, then unnecessary alerts on training seeds.
    selected = min(candidates, key=lambda item: (item["counts"]["fn"], item["counts"]["fp"]))
    output = {
        "selection": "minimize false negatives, then false positives on training steps",
        "training_seeds": sorted(TRAIN), "held_out_seeds": sorted(TEST),
        "candidates": candidates, "selected": selected["threshold"],
        "held_out_counts": counts(validation, selected["threshold"]),
        "scope": "Retrospective classification of steps generated by the fixed 1e10 reconstruction policy.",
    }
    if args.steps.resolve() == args.output.resolve():
        parser.error("input and output must differ")
    with args.output.open("x", encoding="utf-8") as stream:
        json.dump(output, stream, indent=2, allow_nan=False)
        stream.write("\n")
    print(json.dumps({"threshold": output["selected"], "held_out": output["held_out_counts"]}))


if __name__ == "__main__":
    main()
